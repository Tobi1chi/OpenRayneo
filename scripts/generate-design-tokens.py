"""Generate Swift and Kotlin color tokens from VS Code-style theme files.

assets/design-tokens/registry.json lists every semantic token and its purpose; openrayneo-light.json and
openrayneo-dark.json use the VS Code color theme shape ({name, type, colors}) and must define each key.

    uv run python scripts/generate-design-tokens.py
"""

import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / "assets/design-tokens"
swift_out = root / "Sources/OpenRayneoBridge/DesignTokens.swift"
kotlin_out = root / "android/app/src/main/java/com/openrayneo/android/DesignTokens.kt"

registry = json.loads((source / "registry.json").read_text())["colors"]
themes = {kind: json.loads((source / f"openrayneo-{kind}.json").read_text()) for kind in ("light", "dark")}

errors = []
for kind, theme in themes.items():
    if theme["type"] != kind:
        errors.append(f"openrayneo-{kind}.json: type is {theme['type']!r}")
    keys = set(theme["colors"])
    errors += [f"openrayneo-{kind}.json: missing {key}" for key in registry if key not in keys]
    errors += [f"openrayneo-{kind}.json: {key} is not in registry.json" for key in keys - set(registry)]
    errors += [f"openrayneo-{kind}.json: {key} = {value!r} is not #RRGGBB or #RRGGBBAA"
               for key, value in theme["colors"].items() if not re.fullmatch(r"#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?", value)]
if errors:
    sys.exit("\n".join(errors))


def identifier(key: str) -> str:
    """button.secondaryBackground -> buttonSecondaryBackground"""
    head, *rest = key.split(".")
    return head + "".join(part[0].upper() + part[1:] for part in rest)


def rgba(value: str) -> str:
    value = value[1:].upper()
    return value if len(value) == 8 else value + "FF"


header = "Generated by scripts/generate-design-tokens.py from assets/design-tokens. Do not edit by hand."

swift = [
    "// Copyright 2026 Tobi1chi",
    "// SPDX-License-Identifier: Apache-2.0",
    f"// {header}",
    "",
    "import AppKit",
    "import SwiftUI",
    "",
    "/// Semantic color tokens; each resolves to the light or dark theme value with the window appearance.",
    "enum Token {",
]
for key, description in registry.items():
    light, dark = (rgba(themes[kind]["colors"][key]) for kind in ("light", "dark"))
    swift += [f"    /// `{key}`: {description}", f"    static let {identifier(key)} = color(light: 0x{light}, dark: 0x{dark})"]
swift += [
    "",
    "    private static func color(light: UInt32, dark: UInt32) -> Color {",
    "        Color(nsColor: NSColor(name: nil) { appearance in",
    "            let value = appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light",
    "            return NSColor(srgbRed: CGFloat(value >> 24 & 0xFF) / 255, green: CGFloat(value >> 16 & 0xFF) / 255,",
    "                           blue: CGFloat(value >> 8 & 0xFF) / 255, alpha: CGFloat(value & 0xFF) / 255)",
    "        })",
    "    }",
    "}",
    "",
]
swift_out.write_text("\n".join(swift))


def argb(value: str) -> str:
    value = rgba(value)
    return f"0x{value[6:]}{value[:6]}"


kotlin = [
    "// Copyright 2026 Tobi1chi",
    "// SPDX-License-Identifier: Apache-2.0",
    f"// {header}",
    "package com.openrayneo.android",
    "",
    "import androidx.compose.runtime.Composable",
    "import androidx.compose.runtime.Immutable",
    "import androidx.compose.runtime.ReadOnlyComposable",
    "import androidx.compose.runtime.staticCompositionLocalOf",
    "import androidx.compose.ui.graphics.Color",
    "",
    "/** Semantic color tokens; CompanionTheme provides the light or dark set. */",
    "@Immutable",
    "internal class ColorTokens(",
]
for key, description in registry.items():
    kotlin += [f"    /** `{key}`: {description} */", f"    val {identifier(key)}: Color,"]
kotlin.append(")")
for kind in ("light", "dark"):
    kotlin += ["", f"internal val {kind.capitalize()}ColorTokens =", "    ColorTokens("]
    kotlin += [f"        {identifier(key)} = Color({argb(themes[kind]['colors'][key])}),"
               for key in registry]
    kotlin.append("    )")
kotlin += [
    "",
    "internal val LocalColorTokens = staticCompositionLocalOf { LightColorTokens }",
    "",
    "/** The active theme's tokens. */",
    "internal val tokens: ColorTokens",
    "    @Composable @ReadOnlyComposable get() = LocalColorTokens.current",
    "",
]
kotlin_out.write_text("\n".join(kotlin))
print(f"{len(registry)} tokens -> {swift_out.relative_to(root)}, {kotlin_out.relative_to(root)}")
